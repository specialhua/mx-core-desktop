// Command gennav generates the native sidebar from the web admin's route
// metadata, so the desktop app's menu follows apps/admin after an upstream
// update: run `go generate` in apps/desktop and review the diff.
//
// It reads, without running any JavaScript:
//   - apps/admin/src/views/**/page(.sync).tsx: defineMetadata({ titleKey, icon, order, hidden })
//   - apps/admin/src/views/(<section>)/meta.ts: the section's titleKey and order
//   - apps/admin/src/i18n/resources/{zh-CN,en-US}.ts: the titles
//   - lucide-react's icon data: the icons, written as SVG files
//
// The tree mirrors apps/admin/vite-plugins/admin-routes/generate.ts: a page is
// the child of the nearest page whose URL is a prefix of its own, hidden and
// dynamic pages are left out, and the (debug) and (public) sections are not
// in the production sidebar.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type page struct {
	section  string
	url      string
	titleKey string
	icon     string
	order    int
	hidden   bool
	children []*page
}

type section struct {
	name     string
	titleKey string
	order    int
	pages    []*page
}

var (
	reMeta     = regexp.MustCompile(`(?s)defineMetadata\(\{(.*?)\}\)`)
	reTitleKey = regexp.MustCompile(`titleKey:\s*'([^']+)'`)
	reIcon     = regexp.MustCompile(`\bicon:\s*([A-Za-z0-9]+)`)
	reOrder    = regexp.MustCompile(`\border:\s*(-?\d+)`)
	reHidden   = regexp.MustCompile(`\bhidden:\s*true`)
	reI18n     = regexp.MustCompile(`(?m)^\s*'([^']+)':\s*\n?\s*'((?:[^'\\]|\\.)*)'`)
	reSVGNode  = regexp.MustCompile(`\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]`)
	reAlias    = regexp.MustCompile(`export \{ default \} from '\./([\w-]+)\.mjs'`)
	reSVGAttr  = regexp.MustCompile(`(\w+):\s*"([^"]*)"`)
)

func main() {
	admin := flag.String("admin", "../admin", "path to apps/admin")
	lucide := flag.String("lucide", "", "path to lucide-react (default: resolved from apps/admin/node_modules)")
	out := flag.String("out", "nav_gen.go", "the Go file to write")
	icons := flag.String("icons", "icons", "the directory to write the SVG icons to")
	flag.Parse()

	if *lucide == "" {
		*lucide = filepath.Join(*admin, "node_modules", "lucide-react")
	}
	views := filepath.Join(*admin, "src", "views")
	sections, err := scan(views)
	if err != nil {
		log.Fatal(err)
	}
	zh := mustI18n(filepath.Join(*admin, "src", "i18n", "resources", "zh-CN.ts"))
	en := mustI18n(filepath.Join(*admin, "src", "i18n", "resources", "en-US.ts"))

	used := map[string]bool{}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gennav from apps/admin; DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("var navSections = []navSection{\n")
	for _, s := range sections {
		fmt.Fprintf(&b, "{Title: %s, TitleEN: %s, Items: []navItem{\n", lookup(zh, s.titleKey), lookup(en, s.titleKey))
		for _, p := range s.pages {
			writeItem(&b, p, zh, en, used)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("format: %v\n%s", err, b.Bytes())
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}

	if err := os.MkdirAll(*icons, 0o755); err != nil {
		log.Fatal(err)
	}
	names := make([]string, 0, len(used))
	for name := range used {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		svg, err := lucideSVG(*lucide, name)
		if err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(*icons, name+".svg"), svg, 0o644); err != nil {
			log.Fatal(err)
		}
	}
	log.Printf("gennav: %d sections, %d icons", len(sections), len(names))
}

func writeItem(b *bytes.Buffer, p *page, zh, en map[string]string, used map[string]bool) {
	icon := ""
	if p.icon != "" {
		icon = kebab(p.icon)
		used[icon] = true
	}
	fmt.Fprintf(b, "{Path: %q, Title: %s, TitleEN: %s, Icon: %q", p.url, lookup(zh, p.titleKey), lookup(en, p.titleKey), icon)
	if kids := visible(p.children); len(kids) > 0 {
		b.WriteString(", Children: []navItem{\n")
		for _, c := range kids {
			writeItem(b, c, zh, en, used)
		}
		b.WriteString("}")
	}
	b.WriteString("},\n")
}

func scan(views string) ([]*section, error) {
	bySection := map[string]*section{"": {name: "", order: 0}}
	var pages []*page
	err := filepath.WalkDir(views, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(views, path)
		segs := strings.Split(filepath.ToSlash(rel), "/")
		name := segs[len(segs)-1]
		dirs := segs[:len(segs)-1]
		sec := ""
		if len(dirs) > 0 && strings.HasPrefix(dirs[0], "(") {
			sec = strings.Trim(dirs[0], "()")
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if name == "meta.ts" && len(dirs) == 1 && sec != "" {
			s := bySection[sec]
			if s == nil {
				s = &section{name: sec}
				bySection[sec] = s
			}
			if m := reTitleKey.FindSubmatch(src); m != nil {
				s.titleKey = string(m[1])
			}
			if m := reOrder.FindSubmatch(src); m != nil {
				s.order, _ = strconv.Atoi(string(m[1]))
			}
			return nil
		}
		if name != "page.tsx" && name != "page.sync.tsx" {
			return nil
		}
		var urlSegs []string
		for _, d := range dirs {
			if strings.HasPrefix(d, "(") {
				continue
			}
			urlSegs = append(urlSegs, d)
		}
		p := &page{section: sec, url: "/" + strings.Join(urlSegs, "/"), order: 999}
		if m := reMeta.FindSubmatch(src); m != nil {
			meta := m[1]
			if t := reTitleKey.FindSubmatch(meta); t != nil {
				p.titleKey = string(t[1])
			}
			if t := reIcon.FindSubmatch(meta); t != nil {
				p.icon = string(t[1])
			}
			if t := reOrder.FindSubmatch(meta); t != nil {
				p.order, _ = strconv.Atoi(string(t[1]))
			}
			p.hidden = reHidden.Match(meta)
		}
		pages = append(pages, p)
		return nil
	})
	if err != nil {
		return nil, err
	}

	// Group the pages and nest them as buildSectionTree does.
	grouped := map[string][]*page{}
	for _, p := range pages {
		if p.section == "public" || p.section == "debug" || p.section == "dev" {
			continue
		}
		grouped[p.section] = append(grouped[p.section], p)
	}
	var out []*section
	for name, ps := range grouped {
		s := bySection[name]
		if s == nil {
			s = &section{name: name}
		}
		byURL := map[string]*page{}
		for _, p := range ps {
			byURL[p.url] = p
		}
		sort.Slice(ps, func(i, j int) bool {
			di, dj := strings.Count(ps[i].url, "/"), strings.Count(ps[j].url, "/")
			if di != dj {
				return di < dj
			}
			return ps[i].url < ps[j].url
		})
		var roots []*page
		for _, p := range ps {
			segs := strings.Split(strings.Trim(p.url, "/"), "/")
			var parent *page
			for n := len(segs) - 1; n > 0; n-- {
				if q := byURL["/"+strings.Join(segs[:n], "/")]; q != nil {
					parent = q
					break
				}
			}
			if parent != nil {
				parent.children = append(parent.children, p)
			} else {
				roots = append(roots, p)
			}
		}
		s.pages = visible(roots)
		if len(s.pages) > 0 {
			out = append(out, s)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].order != out[j].order {
			return out[i].order < out[j].order
		}
		return out[i].name < out[j].name
	})
	return out, nil
}

// visible keeps the pages the sidebar lists, sorted as sortByOrder does.
func visible(ps []*page) []*page {
	var out []*page
	for _, p := range ps {
		if p.hidden || strings.Contains(p.url, "[") || p.titleKey == "" {
			continue
		}
		out = append(out, p)
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].order != out[j].order {
			return out[i].order < out[j].order
		}
		return out[i].url < out[j].url
	})
	return out
}

func mustI18n(path string) map[string]string {
	src, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	m := map[string]string{}
	for _, kv := range reI18n.FindAllSubmatch(src, -1) {
		m[string(kv[1])] = strings.ReplaceAll(string(kv[2]), `\'`, `'`)
	}
	return m
}

func lookup(m map[string]string, key string) string {
	if key == "" {
		return `""`
	}
	v, ok := m[key]
	if !ok {
		log.Fatalf("missing translation %q", key)
	}
	return strconv.Quote(v)
}

// kebab turns a lucide component name into its file name: FileCode2 →
// file-code-2, BarChart3 → bar-chart-3.
func kebab(s string) string {
	var b strings.Builder
	for i, r := range s {
		prevLower := i > 0 && (s[i-1] >= 'a' && s[i-1] <= 'z')
		prevDigit := i > 0 && (s[i-1] >= '0' && s[i-1] <= '9')
		switch {
		case r >= 'A' && r <= 'Z':
			if i > 0 && (prevLower || prevDigit) {
				b.WriteByte('-')
			}
			b.WriteRune(r + 'a' - 'A')
		case r >= '0' && r <= '9':
			if i > 0 && !prevDigit {
				b.WriteByte('-')
			}
			b.WriteRune(r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func lucideSVG(root, name string) ([]byte, error) {
	src, err := os.ReadFile(filepath.Join(root, "dist", "esm", "icons", name+".mjs"))
	if err != nil {
		return nil, fmt.Errorf("lucide icon %s: %w", name, err)
	}
	// A renamed icon re-exports its new name: bar-chart-3 → chart-column.
	if m := reAlias.FindSubmatch(src); m != nil {
		return lucideSVG(root, string(m[1]))
	}
	nodes := reSVGNode.FindAllSubmatch(src, -1)
	if len(nodes) == 0 {
		return nil, fmt.Errorf("lucide icon %s: no shapes found", name)
	}
	var b bytes.Buffer
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">`)
	for _, n := range nodes {
		fmt.Fprintf(&b, "<%s", n[1])
		for _, a := range reSVGAttr.FindAllSubmatch(n[2], -1) {
			if string(a[1]) == "key" {
				continue
			}
			fmt.Fprintf(&b, ` %s="%s"`, a[1], a[2])
		}
		b.WriteString("/>")
	}
	b.WriteString("</svg>\n")
	return b.Bytes(), nil
}
